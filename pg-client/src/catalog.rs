#[cfg(test)]
mod test {
    use super::*;
    use pretty_assertions::assert_eq;

    #[test]
    fn reads_the_oids_a_server_sends() {
        assert_eq!(Type::from_oid(Oid::new(23)), Type::Builtin(Builtin::Int4));
        assert_eq!(Type::from_oid(Oid::new(25)), Type::Builtin(Builtin::Text));
        assert_eq!(
            Type::from_oid(Oid::new(1007)),
            Type::Builtin(Builtin::Int4Array)
        );
    }

    /// Above `FirstNormalObjectId`, so assigned by a `CREATE` rather than the
    /// catalog.
    #[test]
    fn keeps_an_oid_it_does_not_name() {
        let created = Oid::new(16_384);

        assert_eq!(Type::from_oid(created), Type::Other(created));
        assert_eq!(Builtin::from_oid(created), None);
        assert_eq!(Type::Other(created).oid(), created);
    }

    #[test]
    fn distinguishes_postgresqls_unknown_from_an_unnamed_oid() {
        assert_eq!(
            Type::from_oid(Oid::new(705)),
            Type::Builtin(Builtin::Unknown)
        );
        assert_eq!(Builtin::Unknown.name().as_str(), "unknown");
        assert_ne!(Type::Builtin(Builtin::Unknown), Type::Other(Oid::new(705)));
    }

    #[test]
    fn pairs_an_element_with_its_array() {
        assert_eq!(Builtin::Int4.array(), Some(Builtin::Int4Array));
        assert_eq!(Builtin::Int4Array.element(), Some(Builtin::Int4));

        // Written out in the catalog rather than generated from the element,
        // so it is the one pairing a generator can silently miss.
        assert_eq!(Builtin::Record.array(), Some(Builtin::RecordArray));
        assert_eq!(Builtin::RecordArray.element(), Some(Builtin::Record));
    }

    #[test]
    fn does_not_mistake_typelem_for_an_array_pairing() {
        assert_eq!(Builtin::Int2.array(), Some(Builtin::Int2Array));
        assert_ne!(Builtin::Int2.array(), Some(Builtin::Int2vector));

        assert_eq!(Builtin::Name.element(), None);
        assert_eq!(Builtin::Int2vector.element(), None);
    }

    #[test]
    fn every_type_round_trips_through_its_oid() {
        for oid in 0..20_000u32 {
            let oid = Oid::new(oid);

            assert_eq!(Type::from_oid(oid).oid(), oid);
        }
    }
}
